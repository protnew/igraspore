import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const { chromium } = require('../../../.04-Src/node_modules/playwright');
const outDir = process.argv[2];
fs.mkdirSync(outDir, { recursive: true });
const kill = setTimeout(() => { console.error('SHOT TIMEOUT'); process.exit(2); }, 240000);
const errs = [];
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 180)); });
page.on('pageerror', (e) => errs.push(String(e).slice(0, 180)));
await page.goto('http://127.0.0.1:8795/?lang=es&t=' + Date.now(), { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForSelector('#langSelDrop [data-lang]', { timeout: 15000, state: 'attached' });
const names = await page.evaluate(() => {
  const d = document.getElementById('langSelDrop');
  const wrap = document.getElementById('langSelWrap');
  if (wrap) wrap.style.zIndex = '80';
  d.style.opacity = '1';
  d.style.visibility = 'visible';
  d.style.transform = 'none';
  d.scrollTop = d.scrollHeight;
  return Array.from(d.querySelectorAll('[data-lang]')).map((el) => el.getAttribute('data-lang') + '=' + el.textContent);
});
await page.screenshot({ path: path.join(outDir, 'lang-list-es.png'), timeout: 15000 });
fs.writeFileSync(path.join(outDir, 'lang-list.txt'), names.join('\n') + '\nerrors=' + errs.length + '\n' + errs.join('\n'));
await browser.close();
clearTimeout(kill);
const need = ['Español', 'Türkçe', 'Filipino'];
const blob = names.join(' ');
const miss = need.filter((n) => !blob.includes(n));
console.log('SHOTS', outDir, 'count', names.length, 'miss', miss.join(',') || '-', 'errors', errs.length);
if (miss.length) process.exit(3);
