import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const { chromium } = require('../../../.04-Src/node_modules/playwright');
const outDir = process.argv[2];
fs.mkdirSync(outDir, { recursive: true });
const kill = setTimeout(() => { console.error('SHOT TIMEOUT'); process.exit(2); }, 90000);
const errs = [];
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
page.on('pageerror', (e) => errs.push(String(e).slice(0, 200)));
await page.goto('http://127.0.0.1:8795/?lang=en&t=' + Date.now(), { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForSelector('#startBtn', { timeout: 15000 });
await page.screenshot({ path: path.join(outDir, 'en-menu.png'), timeout: 15000 });
fs.writeFileSync(path.join(outDir, 'en-console.txt'), JSON.stringify({ errors: errs }, null, 2));
await browser.close();
clearTimeout(kill);
console.log('SHOTS', outDir, 'errors', errs.length);
