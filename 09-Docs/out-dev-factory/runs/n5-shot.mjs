import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const { chromium } = require('../../../.04-Src/node_modules/playwright');
const outDir = process.argv[2];
fs.mkdirSync(outDir, { recursive: true });
const kill = setTimeout(() => { console.error('SHOT TIMEOUT'); process.exit(2); }, 90000);
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 160)); });
await page.goto('http://127.0.0.1:8793/', { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForTimeout(500);
await page.screenshot({ path: path.join(outDir, 'lab-root.png'), timeout: 10000 });
const rootUrl = page.url();
await page.goto('http://127.0.0.1:8793/lab/tests', { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForTimeout(400);
await page.screenshot({ path: path.join(outDir, 'lab-tests.png'), timeout: 10000 });
const title = await page.locator('h1').innerText().catch(() => '');
fs.writeFileSync(path.join(outDir, 'lab.txt'), `root=${rootUrl}\ntitle=${title}\nerrors=${errs.length}\n${errs.join('\n')}\n`);
await browser.close();
clearTimeout(kill);
console.log('SHOTS', outDir, 'root', rootUrl, 'title', title, 'errs', errs.length);
